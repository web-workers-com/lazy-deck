/**
 * Writes the plugin's language files from locales/<lang>.json (German text →
 * translation) and the key names on the website (website/src/i18n/keys):
 *   <lang>.json in the plugin   action names and tooltips for Stream Deck's
 *                               action list, plus "Localization" for the plugin
 *   ui/libs/locales.js          the texts of the settings pages
 * Run after generate-manifest and i18n-strings.
 */
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const plugin = join(root, "com.lazydeck.plugin.sdPlugin");
const PREFIX = "com.lazydeck.plugin.";

/** Stream Deck language → file of the website's key texts. */
const LANGS = { de: "source.de", en: "en", es: "es", fr: "fr", ja: "ja", ko: "ko", zh_CN: "zh", zh_TW: "zh-tw" };

const json = async (p, fallback) => (existsSync(p) ? JSON.parse(await readFile(p, "utf8")) : fallback);
const manifest = await json(join(plugin, "manifest.json"));
const source = await json(join(root, "locales", "source.json"), {});
const pageTexts = Object.keys(source).filter((k) => source[k].includes("ui/"));

const forPages = {};
const missing = [];
for (const [lang, keysFile] of Object.entries(LANGS)) {
	const table = lang === "de" ? {} : await json(join(root, "locales", `${lang}.json`), {});
	const keys = await json(join(root, "website", "src", "i18n", "keys", `${keysFile}.json`), {});
	const tr = (de) => (lang === "de" ? de : (table[de] ?? de));
	if (lang !== "de") {
		const gaps = Object.keys(source).filter((k) => !(k in table));
		if (gaps.length) missing.push(`${lang}: ${gaps.length}`);
	}

	const file = { Name: "Lazy Deck", Description: tr(manifest.Description), Category: "Lazy Deck" };
	for (const a of manifest.Actions) {
		const k = keys[a.UUID.slice(PREFIX.length)];
		const name = k?.name ?? tr(a.Name);
		const tooltip = k?.text ?? (a.Tooltip ? tr(a.Tooltip) : undefined);
		file[a.UUID] = { Name: name, ...(tooltip ? { Tooltip: tooltip } : {}) };
	}
	file.Localization = lang === "de" ? {} : Object.fromEntries(Object.keys(source).filter((k) => k in table).map((k) => [k, table[k]]));
	await writeFile(join(plugin, `${lang}.json`), `${JSON.stringify(file, null, "\t")}\n`);
	if (lang !== "de") forPages[lang] = Object.fromEntries(pageTexts.filter((k) => k in table).map((k) => [k, table[k]]));
}

await writeFile(
	join(plugin, "ui", "libs", "locales.js"),
	`/* Generated by scripts/generate-locales.mjs: settings page texts, German → language. */\nwindow.LD_LOCALES = ${JSON.stringify(forPages)};\n`,
);
console.log(`locales: ${Object.keys(LANGS).length} languages, ${Object.keys(source).length} texts${missing.length ? `, missing ${missing.join(", ")}` : ""}`);
